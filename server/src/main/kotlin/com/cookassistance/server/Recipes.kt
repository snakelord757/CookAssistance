package com.cookassistance.server

import kotlinx.serialization.Serializable

@Serializable
data class Ingredient(val name: String, val amount: Double, val unit: String)

@Serializable
data class Recipe(
    val id: String,
    val title: String,
    val description: String,
    val type: String,
    val ingredients: List<Ingredient>,
    val steps: List<String>,
    val cookingTimeMin: Int,
    val servings: Int,
    val imageUrl: String,
    val collections: List<String>,
)

@Serializable
data class CollectionInfo(val id: String, val title: String, val description: String)

@Serializable
data class ErrorReply(val error: String)

@Serializable
data class FeedbackRequest(val message: String, val contact: String = "")

@Serializable
data class FeedbackReply(val status: String)

